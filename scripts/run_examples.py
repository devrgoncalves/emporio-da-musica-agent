"""Runs the example conversations against the real agent and saves them to examples/*.md.

Usage:  python scripts/run_examples.py
Each scenario runs in its own thread (fresh memory). Tool calls are recorded
so the reader can see when the agent consulted data or policies.
"""

import json
import os
import sys
import time
import uuid
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from emporio.agent import DEFAULT_MODEL, build_agent, chat  # noqa: E402
from emporio.prompts import STORE_TZ  # noqa: E402

SCENARIOS = [
    (
        "01_catalog_search",
        "Catalog search with price filter (browsing only shows items in stock)",
        ["Quais opções de violões disponíveis custando até R$1000?", "Prefiro de cordas de aço. Qual você indica?"],
    ),
    (
        "02_price_and_payment",
        "Price lookup, PIX discount and installment rules (data + policy)",
        ["Quanto custa o Takamine GD20?", "Se eu pagar no PIX fica quanto? E dá pra parcelar em 12x?"],
    ),
    (
        "03_store_info",
        "General store information (policy)",
        ["Qual o endereço da loja?", "Vocês abrem no sábado?"],
    ),
    (
        "04_return_request_non_trivial",
        "NON-TRIVIAL: return request with identity check, order data and return/warranty deadlines",
        [
            "Me arrependi da minha compra, posso devolver meu pedido?",
            "Pedido 4, e-mail lucas.mendes@jmail.com",
            "E se o violão estiver com defeito?",
        ],
    ),
    (
        "05_out_of_scope_and_stock",
        "Out of scope (accessories, unrelated topic), out-of-stock product and English customer",
        [
            "Hi! Do you sell guitar strings?",
            "Ok. Who won the last World Cup?",
            "Fine. Is the Giannini GF-3D in stock?",
        ],
    ),
]


def render(title: str, turns: list[tuple[str, object]], model: str) -> str:
    now = datetime.now(STORE_TZ)
    lines = [f"# {title}", "", f"_Generated by `scripts/run_examples.py` on {now:%Y-%m-%d %H:%M} (UTC-4) with `{model}`._", ""]
    for message, turn in turns:
        lines += [f"**Cliente:** {message}", ""]
        for call in turn.tool_calls:
            lines.append(f"> 🔧 `{call['name']}({json.dumps(call['args'], ensure_ascii=False)})`")
        if turn.tool_calls:
            lines.append("")
        lines += [f"**Tom (agente):** {turn.reply}", "", "---", ""]
    return "\n".join(lines)


def main():
    agent = build_agent()
    model = os.getenv("GEMINI_MODEL") or DEFAULT_MODEL
    out_dir = ROOT / "examples"
    out_dir.mkdir(exist_ok=True)
    only = set(sys.argv[1:])
    for slug, title, messages in SCENARIOS:
        if only and slug not in only:
            continue
        thread = str(uuid.uuid4())
        turns = []
        for message in messages:
            turns.append((message, chat(agent, thread, message)))
            time.sleep(4)  # stay under the free tier requests-per-minute limit
        (out_dir / f"{slug}.md").write_text(render(title, turns, model), encoding="utf-8")
        print(f"saved examples/{slug}.md")


if __name__ == "__main__":
    main()
